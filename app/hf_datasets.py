"""Sync layer for the Orchestrator's durable state, all hosted in one HF
bucket (configs/hf_datasets.yaml -> hf://buckets/mflux-community/ci).

Design (2026-08-19): local files under data/ (models_hf.json, models_missing.json,
runpod_gpu_skus.json, logs/devops.jsonl, logs/conversions.jsonl, models_queue.json)
are caches of what's durably stored in the bucket -- the "ephemeral Orchestrator"
property is that any of them can be regenerated by pull()ing from the bucket, so
losing local disk never loses state. models_mflux.json is the one exception:
it's owned by the upstream mflux CI pipeline (writable: false in config), we only
ever pull it.

Uses huggingface_hub's bucket-native API (get_bucket_paths_info/download_bucket_files/
batch_bucket_files), not the model/dataset-repo APIs (hf_hub_download/upload_file) --
buckets are a distinct HF resource type, confirmed live 2026-08-19 via
huggingface_hub 1.27.0's exports (BucketFile.xet_hash is the same content hash
returned by a plain HEAD request's x-xet-hash header, verified against the live
bucket: both gave fbf80c1a0572d0cf3710888fb4e9be129f85d7a0deba91af1174d537c38de97c
for models_mflux.json).

Change detection: get_bucket_paths_info() is metadata-only (no download) and
returns each file's current xet_hash. pull() compares that against the last-seen
hash recorded in data/.hf_sync_state.json and only calls download_bucket_files()
when it differs -- so polling for updates is cheap even though the files can be
tens of KB.
"""

import json
import os
from datetime import datetime, timezone
from pathlib import Path

CONFIG_PATH = Path(__file__).resolve().parent.parent / "configs" / "hf_datasets.yaml"
SYNC_STATE_PATH = Path(
    os.environ.get(
        "HF_SYNC_STATE_PATH",
        Path(__file__).resolve().parent.parent / "data" / ".hf_sync_state.json",
    )
)


class HfDatasetConfigError(RuntimeError):
    """Raised for an unknown dataset name, a push against a non-writable
    dataset, or a missing HF_TOKEN -- a config/request problem, not a bare
    500. Same pattern as app.outbox.OutboxConfigError."""


def load_dataset_config() -> dict:
    import yaml

    with open(CONFIG_PATH, encoding="utf-8") as f:
        return yaml.safe_load(f)


def _local_path(entry: dict) -> Path:
    """Resolve entry['local_path'] against the repo root (CONFIG_PATH's
    grandparent), not the process's current working directory -- matches
    the file-relative-path convention every other app/*.py module already
    uses (models_hf.py, models_mflux.py, queue_store.py, runpod_skus.py),
    so pull()/push() find the same file regardless of what cwd the
    Orchestrator happens to be launched from. Absolute paths pass through
    unchanged."""
    path = Path(entry["local_path"])
    return path if path.is_absolute() else CONFIG_PATH.parent.parent / path


def _dataset(name: str) -> tuple[str, dict]:
    config = load_dataset_config()
    entry = config.get("datasets", {}).get(name)
    if entry is None:
        raise HfDatasetConfigError(
            f"no such dataset {name!r} in {CONFIG_PATH} -- known: "
            f"{sorted(config.get('datasets', {}))}"
        )
    return config["bucket_id"], entry


def _token() -> str:
    token = os.environ.get("HF_TOKEN")
    if not token:
        raise HfDatasetConfigError("HF_TOKEN must be set in the environment")
    return token


def _load_sync_state() -> dict:
    if not SYNC_STATE_PATH.exists():
        return {}
    try:
        return json.loads(SYNC_STATE_PATH.read_text())
    except (OSError, json.JSONDecodeError):
        # Same reasoning as app.models_hf.load_models_hf: a corrupt state
        # file should degrade to "nothing known yet", not break every sync.
        return {}


def _write_sync_state(state: dict) -> None:
    import tempfile

    SYNC_STATE_PATH.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=SYNC_STATE_PATH.parent, delete=False
    ) as tmp:
        json.dump(state, tmp, indent=2)
        tmp_path = Path(tmp.name)
    tmp_path.replace(SYNC_STATE_PATH)


def list_datasets() -> list[dict]:
    """Every configured dataset plus its last-known sync state -- backs
    GET /datasets."""
    config = load_dataset_config()
    state = _load_sync_state()
    result = []
    for name, entry in config.get("datasets", {}).items():
        local_path = _local_path(entry)
        result.append({
            "name": name,
            "bucket_id": config["bucket_id"],
            "path_in_repo": entry["path_in_repo"],
            "local_path": entry["local_path"],
            "writable": entry.get("writable", True),
            "local_exists": local_path.exists(),
            "local_mtime": (
                datetime.fromtimestamp(local_path.stat().st_mtime, tz=timezone.utc).isoformat()
                if local_path.exists()
                else None
            ),
            "last_known": state.get(name),
        })
    return result


def pull(name: str) -> dict:
    """Fetch the dataset's current content hash from the bucket (metadata
    only -- no download) and compare to what we last saw. Downloads and
    overwrites the local cache only if it changed. Returns
    {"changed": bool, "xet_hash": str, "size": int}."""
    from huggingface_hub import download_bucket_files, get_bucket_paths_info

    bucket_id, entry = _dataset(name)
    path_in_repo = entry["path_in_repo"]
    local_path = _local_path(entry)
    token = _token()

    files = list(get_bucket_paths_info(bucket_id, [path_in_repo], token=token))
    if not files:
        raise HfDatasetConfigError(
            f"{path_in_repo!r} not found in bucket {bucket_id!r} -- nothing to pull"
        )
    remote = files[0]

    state = _load_sync_state()
    previous = state.get(name, {})
    # Also re-download if the local file is simply gone -- the sync-state
    # hash matching doesn't mean the file survived (e.g. a fresh checkout,
    # or someone deleted data-hf-sync/ but not .hf_sync_state.json). That's
    # exactly the "ephemeral Orchestrator" scenario this module exists for.
    changed = previous.get("xet_hash") != remote.xet_hash or not local_path.exists()

    if changed:
        local_path.parent.mkdir(parents=True, exist_ok=True)
        download_bucket_files(bucket_id, [(path_in_repo, local_path)], token=token)

    state[name] = {
        "xet_hash": remote.xet_hash,
        "size": remote.size,
        "checked_at": datetime.now(timezone.utc).isoformat(),
    }
    _write_sync_state(state)

    return {"changed": changed, "xet_hash": remote.xet_hash, "size": remote.size}


def push(name: str) -> dict:
    """Upload the local file to the bucket, overwriting whatever's there.
    Refuses (HfDatasetConfigError) for a dataset marked writable: false --
    e.g. models_mflux.json, which the upstream mflux CI pipeline owns."""
    from huggingface_hub import batch_bucket_files, get_bucket_paths_info

    bucket_id, entry = _dataset(name)
    if not entry.get("writable", True):
        raise HfDatasetConfigError(f"{name!r} is not writable (owned by another pipeline)")

    path_in_repo = entry["path_in_repo"]
    local_path = _local_path(entry)
    if not local_path.exists():
        raise HfDatasetConfigError(f"{local_path} does not exist -- nothing to push")
    token = _token()

    batch_bucket_files(bucket_id, add=[(local_path, path_in_repo)], token=token)

    # Re-read the now-current remote hash rather than hashing the local file
    # ourselves, so pull() and push() agree on exactly what "in sync" means.
    files = list(get_bucket_paths_info(bucket_id, [path_in_repo], token=token))
    remote = files[0]

    state = _load_sync_state()
    state[name] = {
        "xet_hash": remote.xet_hash,
        "size": remote.size,
        "checked_at": datetime.now(timezone.utc).isoformat(),
    }
    _write_sync_state(state)

    return {"pushed": True, "xet_hash": remote.xet_hash, "size": remote.size}
